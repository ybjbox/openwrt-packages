#!/bin/sh
# 把 luci-app-cf-ipcheck/src/ 按 manifest 拼成运行时单个 settings.js / settings.css。
#
#   sh tools/build-view.sh            # 生成产物（会覆盖 htdocs 里的两个文件）
#   sh tools/build-view.sh --check    # 只校验：产物与源一致、ES5 黑名单、CSS 守卫、版本一致
#
# 产物头部写 src-sha256，--check 用同一算法重算后逐字节比对。
# 产物永远不手改；评审只读 src/。
set -u

ROOT=$(CDPATH= cd "$(dirname "$0")/.." 2>/dev/null && pwd) || exit 1
PKG="$ROOT/luci-app-cf-ipcheck"
SRC=${CFI_SRC:-$PKG/view-src}
OUTDIR=${CFI_OUT:-$PKG/htdocs/luci-static/resources/view/cf_ipcheck}
MANIFEST="$SRC/manifest.txt"
OUTJS="$OUTDIR/settings.js"
OUTCSS="$OUTDIR/settings.css"
TMPD=${TMPDIR:-/tmp}/cfi-build.$$
CHECK=0

for a in "$@"; do
	case "$a" in
		--check) CHECK=1 ;;
		--src) shift; SRC=$1 ;;
		--out) shift; OUTDIR=$1 ;;
		-h|--help) sed -n '2,9p' "$0"; exit 0 ;;
		*) echo "unknown arg: $a" >&2; exit 2 ;;
	esac
done
MANIFEST="$SRC/manifest.txt"
OUTJS="$OUTDIR/settings.js"
OUTCSS="$OUTDIR/settings.css"

fail() { echo "[FAIL] $*" >&2; exit 1; }

[ -f "$MANIFEST" ] || fail "缺 manifest：$MANIFEST"
# src 必须在 htdocs 之外：luci.mk 只装 htdocs/ 与 root/，其它目录不会进固件。
case "$SRC" in
	*/htdocs/*) fail "src/ 不能放在 htdocs 下（会被装进固件）：$SRC" ;;
esac

mkdir -p "$TMPD" || fail "建不了临时目录"
trap 'rm -rf "$TMPD"' EXIT INT TERM

# ---- 读 manifest：js / css 两类，顺序即拼接顺序 ----------------------------
: > "$TMPD/js.list"
: > "$TMPD/css.list"
while IFS= read -r line; do
	case "$line" in
		''|'#'*) continue ;;
	esac
	kind=${line%% *}
	rel=${line#* }
	[ "$kind" = "$line" ] && fail "manifest 行没有类型前缀：$line"
	case "$kind" in
		js) echo "$rel" >> "$TMPD/js.list" ;;
		css) echo "$rel" >> "$TMPD/css.list" ;;
		*) fail "manifest 未知类型 <$kind>：$line" ;;
	esac
done < "$MANIFEST"

# ---- 源一致性：文件必须存在、不许空 ----------------------------------------
for list in "$TMPD/js.list" "$TMPD/css.list"; do
	while IFS= read -r rel; do
		f="$SRC/$rel"
		[ -f "$f" ] || fail "manifest 指向的文件不存在：src/$rel"
		[ -s "$f" ] || fail "源文件是空的：src/$rel"
	done < "$list"
done

# ---- ES5 黑名单（JsMin 是字符级压缩器，不认新语法边界） ---------------------
while IFS= read -r rel; do
	f="$SRC/$rel"
	if grep -nE '=>|`|\blet[[:space:]]+[A-Za-z_$]|\bconst[[:space:]]+[A-Za-z_$]|\bclass[[:space:]]+[A-Za-z_$]|\.\.\.' "$f" > "$TMPD/hit" 2>/dev/null; then
		echo "[FAIL] src/$rel 含 ES5 以外的语法（JsMin 会切坏）：" >&2
		sed 's/^/    /' "$TMPD/hit" >&2
		exit 1
	fi
done < "$TMPD/js.list"

# ---- CSS 守卫：只允许一个源文件；禁 !important ----------------------------
# CssTidy 会合并选择器、且对 htdocs 下每个 css 单独压缩。多文件时「文件顺序
# 即优先级」在构建后不可依赖，也平白多几个请求 —— 所以 CSS 只留一个源文件，
# 内部按段注释组织。JS 不受这条限制（拼接后只有一个文件）。
if [ -s "$TMPD/css.list" ]; then
	ncss=$(grep -c . "$TMPD/css.list" 2>/dev/null)
	[ -n "$ncss" ] || ncss=0
	if [ "$ncss" -gt 1 ]; then
		echo "[FAIL] CSS 源文件有 $ncss 个；只允许一个（CssTidy 合并选择器后跨文件顺序不可依赖）" >&2
		sed 's/^/    /' "$TMPD/css.list" >&2
		exit 1
	fi
	while IFS= read -r rel; do
		f="$SRC/$rel"
		if grep -n '!important' "$f" > "$TMPD/hit" 2>/dev/null; then
			echo "[FAIL] src/$rel 里有 !important（构建期合并选择器后行为不可控）：" >&2
			sed 's/^/    /' "$TMPD/hit" >&2
			exit 1
		fi
	done < "$TMPD/css.list"
fi

# ---- 版本一致：view 里的 rN 必须等于 Makefile 的 PKG_RELEASE -----------------
PRE="$SRC/$(head -n 1 "$TMPD/js.list")"
build=$(sed -n "s/.*VIEW_BUILD = 'r\([0-9]*\)'.*/\1/p" "$PRE" | head -n 1)
mkrel=$(sed -n 's/^PKG_RELEASE:=[[:space:]]*\([0-9]*\).*/\1/p' "$PKG/Makefile" | head -n 1)
[ -n "$build" ] || fail "src 里找不到 VIEW_BUILD = 'rN'"
[ "$build" = "$mkrel" ] || fail "VIEW_BUILD r$build != PKG_RELEASE ${mkrel:-<无>}"

# ---- 计算 src 指纹（manifest + 所有被引用文件，顺序敏感） -------------------
hash_all() {
	{
		cat "$MANIFEST"
		while IFS= read -r rel; do cat "$SRC/$rel"; done < "$TMPD/js.list"
		while IFS= read -r rel; do cat "$SRC/$rel"; done < "$TMPD/css.list"
	} | sha256sum | cut -d' ' -f1
}
HASH=$(hash_all)
[ -n "$HASH" ] || fail "算不出 src 指纹（缺 sha256sum？）"

# ---- 拼接 -------------------------------------------------------------------
: > "$TMPD/settings.js"
printf '/* AUTO-GENERATED by tools/build-view.sh — do not edit. src-sha256: %s */\n' "$HASH" >> "$TMPD/settings.js"
while IFS= read -r rel; do
	printf '\n/* ===== src/%s ===== */\n' "$rel" >> "$TMPD/settings.js"
	cat "$SRC/$rel" >> "$TMPD/settings.js"
	printf '\n' >> "$TMPD/settings.js"
done < "$TMPD/js.list"

: > "$TMPD/settings.css"
printf '/* AUTO-GENERATED by tools/build-view.sh — do not edit. src-sha256: %s */\n' "$HASH" >> "$TMPD/settings.css"
while IFS= read -r rel; do
	printf '\n/* ===== src/%s ===== */\n' "$rel" >> "$TMPD/settings.css"
	cat "$SRC/$rel" >> "$TMPD/settings.css"
	printf '\n' >> "$TMPD/settings.css"
done < "$TMPD/css.list"

if [ "$CHECK" = 1 ]; then
	[ -f "$OUTJS" ] || fail "产物不存在：$OUTJS"
	[ -f "$OUTCSS" ] || fail "产物不存在：$OUTCSS"
	cmp -s "$TMPD/settings.js" "$OUTJS" || fail "settings.js 与 src 不一致（改完 src 要重新跑 sh tools/build-view.sh）"
	cmp -s "$TMPD/settings.css" "$OUTCSS" || fail "settings.css 与 src 不一致（改完 src 要重新跑 sh tools/build-view.sh）"
	echo "[PASS] view artifact up to date (src-sha256 $HASH, build r$build)"
	exit 0
fi

mkdir -p "$OUTDIR" || fail "建不了输出目录：$OUTDIR"
cp "$TMPD/settings.js" "$OUTJS" || fail "写不进 $OUTJS"
cp "$TMPD/settings.css" "$OUTCSS" || fail "写不进 $OUTCSS"
echo "[OK] built r$build  js=$(wc -c < "$OUTJS")B css=$(wc -c < "$OUTCSS")B  src-sha256 $HASH"
