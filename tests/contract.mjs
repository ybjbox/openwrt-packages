/* 契约测试：只读引擎 / ucode / ACL / 默认配置 / 构建产物，不依赖视图形状。
 * 运行：node tests/contract.mjs */
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const pkg = path.join(root, 'luci-app-cf-ipcheck');
const ENGINE = path.join(pkg, 'root/usr/bin/cf-ipcheck');
const UC = path.join(pkg, 'root/usr/share/rpcd/ucode/luci.cf-ipcheck');
const ACL = path.join(pkg, 'root/usr/share/rpcd/acl.d/luci-app-cf-ipcheck.json');
const CONF = path.join(pkg, 'root/etc/config/cf_ipcheck');
const VIEW = path.join(pkg, 'htdocs/luci-static/resources/view/cf_ipcheck/settings.js');
const MK = path.join(pkg, 'Makefile');

const read = (p) => fs.readFileSync(p, 'utf8');
let n = 0;
function ok(name, cond, detail) {
	n++;
	if (cond)
		console.log('[PASS] ' + name);
	else {
		console.log('[FAIL] ' + name + (detail ? ' — ' + detail : ''));
		process.exitCode = 1;
	}
}

const engine = read(ENGINE);
const uc = read(UC);
const acl = read(ACL);
const conf = read(CONF);
const view = read(VIEW);

/* ---- 引擎分派标签 ------------------------------------------------------ */
const labels = [...engine.matchAll(/^\t([a-z][a-z_-]*)\)/gm)].map((m) => m[1]);
ok('引擎分派表至少 15 个公开子命令', labels.length >= 15, String(labels.length));
for (const cmd of [ 'status', 'logs', 'show', 'csv', 'pool', 'canary', 'check-sources',
	'dns-sync', 'colo', 'stop', 'run', 'run-now', 'daemon', 'diag', 'selftest' ])
	ok('引擎有子命令 ' + cmd, labels.includes(cmd));

/* ---- ucode ↔ 引擎 ↔ ACL ------------------------------------------------ */
const pairs = [...uc.matchAll(/([a-z_]+):\s*\{[^}]*=>\s*sh\('([a-z-]+)'\)/g)]
	.map((m) => [ m[1], m[2] ]);
ok('ucode 插件 9 个方法', pairs.length === 9, String(pairs.length));
for (const [ method, sub ] of pairs) {
	ok(`${method} → 引擎子命令 ${sub}`, labels.includes(sub));
	ok(`ACL 放开 ${method}`, new RegExp('"' + method + '"').test(acl));
}
ok('ACL 读 6 个方法', /"read"[\s\S]*?"ubus"[\s\S]*?"status"/.test(acl));
ok('ACL 写 3 个方法（run/stop/dns_sync）',
	[ 'run', 'stop', 'dns_sync' ].every((m) => new RegExp('"' + m + '"').test(acl)));

/* ---- 视图声明的方法与 ACL/ucode 对齐（从构建产物里读声明表） ---------- */
const viewMethods = [...view.matchAll(/method:\s*'([a-z_]+)'/g)].map((m) => m[1]).sort();
ok('视图声明 9 个方法', viewMethods.length === 9, viewMethods.join(','));
for (const [ method ] of pairs)
	ok('视图声明了 ' + method, viewMethods.includes(method));
ok('RPC 对象名一致', /var RPC_OBJECT = 'luci\.cf-ipcheck'/.test(view) && /luci\.cf-ipcheck/.test(uc));

/* ---- JSON 契约键（引擎写、视图读） ------------------------------------ */
const STATUS = 'state started finished pool qualified usable intercepted counts domains items reason budget port enabled interval stage stage_done stage_total upload dc_show'.split(' ');
const ITEMS = 'ip code connect_ms tls_ms ttfb_ms total_ms colo speed_mbytes domain loss jitter_ms net_ttfb_ms ray_ok'.split(' ');
const SOURCES = 'url http rc ips cf_in'.split(' ');
for (const k of [ ...STATUS, ...ITEMS, ...SOURCES ]) {
	const inEngine = new RegExp('"' + k + '":').test(engine.replace(/\\/g, ''));
	const inView = view.includes(k);
	ok(`契约键 ${k} 两边都在`, inEngine && inView, `engine=${inEngine} view=${inView}`);
}
for (const k of [ 'next_run', 'dc_summary', 'dc_pick', 'dc_show', 'probe_metric',
	'speed_unit', 'speed_mode', 'bypass', 'items_total', 'speed_bps' ])
	ok(`扩展键 ${k} 页面在读`, view.includes(k));
ok('吞吐废弃键不进视图', !/speed_mbps|speed_mibs/.test(view));

/* ---- uci：默认配置 ↔ 引擎读取 ↔ 视图字段 ------------------------------ */
const confKeys = [...conf.matchAll(/^\toption\s+([a-z_]+)/gm)].map((m) => m[1]);
ok('默认配置 55 个 option', confKeys.length === 55, String(confKeys.length));
const fields = [...view.matchAll(/field\([a-z]+, '[A-Za-z]+', form\.[A-Za-z]+, '([a-z_]+)'/g)]
	.map((m) => m[1]);
ok('视图 field() 声明 53 个字段', fields.length === 53, String(fields.length));
for (const k of fields)
	ok('字段 ' + k + ' 在默认配置里', confKeys.includes(k));
ok('隐藏兼容键保留但不在界面', confKeys.includes('dns_record') && confKeys.includes('dns_proxied') &&
	!fields.includes('dns_record') && !fields.includes('dns_proxied'));
ok('源清单单独声明且只有一处', (view.match(/option\(form\.DynamicList, 'community_sources'/g) || []).length === 1);

/* ---- 版本 ------------------------------------------------------------- */
const mk = read(MK);
const rel = (mk.match(/PKG_RELEASE:=(\d+)/) || [])[1];
const vb = (view.match(/VIEW_BUILD = 'r(\d+)'/) || [])[1];
ok('VIEW_BUILD == PKG_RELEASE', rel && rel === vb, `${vb} vs ${rel}`);

/* ---- 构建产物指纹 ----------------------------------------------------- */
ok('产物带 src-sha256 头', /AUTO-GENERATED by tools\/build-view\.sh .* src-sha256: [0-9a-f]{64}/.test(view));

console.log(`\n契约测试：${n} 条，失败 ${process.exitCode ? '有' : '0'}`);
